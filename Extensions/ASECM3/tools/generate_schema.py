"""Generate bounded native format metadata from the credited M3 schema.
No runtime Python dependency. No parser implementation is imported.
"""
from pathlib import Path
from functools import lru_cache
import hashlib
import json
import re
import xml.etree.ElementTree as ET
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "schema/structures.xml"
structures = {e.get("name"): e for e in ET.parse(SOURCE).getroot().findall("structure")}
primitive = {"uint8": 1, "int16": 2, "uint16": 2, "int32": 4, "uint32": 4,
             "uint64": 8, "float": 4}
@lru_cache(None)
def layout(name, version, md):
    node = structures[name]
    declared = {int(v.get("number")): int(v.get("size")) for v in node.findall("versions/version")}
    if version not in declared:
        raise ValueError((name, version, "unknown layout"))
    offset, fields = 0, []
    selected = {}
    for field in node.findall("fields/field"):
        if int(field.get("since_version", "0")) <= version <= int(field.get("till_version", str(max(declared)))):
            selected[field.get("name")] = field
    # The source schema contains repeated PHSH field names; its established
    # resolver uses the final declaration at the first declaration's position.
    for field in selected.values():
        field_name, kind = field.get("name"), field.get("type")
        nested = []
        ref_tag = ""
        if kind in primitive:
            size = primitive[kind]
        elif kind is None:
            size, kind = int(field.get("size")), "bytes"
        else:
            match = re.fullmatch(r"(.+)V(\d+)", kind)
            child, child_version = (match[1], int(match[2])) if match else (kind, 0)
            if md == 33 and child == "Reference":
                child = "SmallReference"
            size, children = layout(child, child_version, md)
            if child in ("Reference", "SmallReference"):
                kind, ref_tag = "reference", field.get("ref_to", field.get("refTo", ""))
            else:
                kind = "record"
                nested = [(field_name+"."+n, offset+o, s, k, r) for n,o,s,k,r in children]
        fields.append((field_name, offset, size, kind, ref_tag))
        fields.extend(nested)
        offset += size
    if md == 34 and offset != declared[version]:
        raise ValueError((name, version, offset, declared[version]))
    return offset, fields
rows, fields = [], []
for name, node in sorted(structures.items()):
    for md in (33,34):
        for ver in sorted(int(e.get("number")) for e in node.findall("versions/version")):
            size, fs = layout(name, ver, md)
            rows.append((name, ver, md, size, len(fields), len(fs)))
            fields.extend(fs)
quote = json.dumps
out = ["// Generated by tools/generate_schema.py; see NOTICE.md for schema credits.",
       "// Schema SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
       "static const Field kFields[] = {"]
for name,offset,size,kind,ref in fields:
    out.append("    {%s, %d, %d, %s, %s}," % (quote(name),offset,size,quote(kind),quote(ref)))
out.append("};\nstatic const Layout kLayouts[] = {")
for name,ver,md,size,first,count in rows:
    out.append("    {%s, %d, %d, %d, kFields+%d, %d}," % (quote(name),ver,md,size,first,count))
out.append("};\n")
(ROOT / "src/Schema.generated.inc").write_text("\n".join(out), encoding="utf-8")
print(f"Generated {len(rows)} layouts and {len(fields)} field descriptors")
