"""Compile Distortion.hlsl into embedded D3D9 bytecode; no runtime compiler."""
from pathlib import Path
import hashlib,subprocess,tempfile
root=Path(__file__).resolve().parents[1]
source=root/'shaders/Distortion.hlsl'
fxc=sorted(Path(r'C:\Program Files (x86)\Windows Kits\10\bin').glob('*/x64/fxc.exe'))[-1]
lines=['// Generated by tools/generate_distortion_shader.py','// HLSL SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()]
with tempfile.TemporaryDirectory(prefix='asecm3-hlsl-') as temp:
 for target,name,defines in [('vs_3_0','distortionVS',['ASEC_VERTEX=1']),('ps_3_0','distortionPS',[])]:
  output=Path(temp)/(name+'.bin')
  args=[str(fxc),'/nologo','/T',target,'/E','Main','/O3','/Fo',str(output)]
  for define in defines:args+=['/D',define]
  subprocess.run([*args,str(source)],check=True)
  data=output.read_bytes();lines.append('static const unsigned char '+name+'[] = {')
  for offset in range(0,len(data),24):lines.append(','.join(str(v) for v in data[offset:offset+24])+',')
  lines.append('};');print(name,len(data),'bytes')
(root/'client/DistortionShader.generated.inc').write_text('\n'.join(lines)+'\n',encoding='utf-8')
