"""Generate native metadata from the copied, source-backed semantic inputs.

Python is a build maintenance tool only; the installed client uses native data.
"""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
def norm(s): return ''.join(c for c in s.casefold() if c.isalnum())
def q(s): return json.dumps(s, ensure_ascii=True)
paths = [DATA/name for name in ('animation_data.csv','animation_id_overrides.json','hots_animation_contexts.json')]
lines = ['// Generated by tools/generate_semantics.py. Do not edit.']
for path in paths:
    lines.append('// Input SHA256: ' + path.name + ' ' + hashlib.sha256(path.read_bytes()).hexdigest())
contexts = json.loads((DATA/'hots_animation_contexts.json').read_text(encoding='utf-8'))
lines += ['static const char* knownTokens[] = {']
lines += [q(t.casefold()) + ',' for t in contexts['tokens']]
lines += ['};', 'static const NameID wrathNames[] = {']
for line in (DATA/'animation_data.csv').read_text(encoding='utf-8-sig').splitlines():
    i, _, name = line.partition(';')
    if i.isdigit() and 0 <= int(i) <= 505:
        lines.append('{'+q(norm(name))+','+str(int(i))+'},')
lines += ['};', 'static const ActorState actorStates[] = {']
for hero, data in contexts['heroes'].items():
    for actor in data.get('actors', []):
        if actor['actor'].casefold() != 'hero'+hero: continue
        for group in actor['stealth_groups']:
            lines.append('{'+q(hero)+','+q(group['group'])+'},')
lines += ['};','static const ActorQuery actorQueries[] = {']
for hero, data in contexts['heroes'].items():
    for actor in data.get('actors', []):
        if actor['actor'].casefold() != 'hero'+hero: continue
        for query in actor['queries']:
            weapon = query['terms'].startswith('WeaponStart.') and '.AttackStart' in query['terms']
            lines.append('{'+q(hero)+','+q(' '.join(sorted(set(query['tokens']))))+','+str(weapon).lower()+'},')
lines += ['};', 'static const Policy policies[] = {']
policies = json.loads((DATA/'animation_id_overrides.json').read_text(encoding='utf-8'))
def emit(model, name, index, p):
    if isinstance(p, int): p = {'animation_id': p}
    vals = [q(norm(model)),q(norm(name)),str(index),str(p.get('animation_id',-1)),
            str(p.get('exclude',False)).lower(),str(p.get('global_sequence',False)).lower(),
            str('exclude' in p).lower(),str('global_sequence' in p).lower(),
            str(p.get('frequency_weight',1)),str('frequency_weight' in p).lower()]
    lines.append('{'+','.join(vals)+'},')
for name, policy in policies['global'].items(): emit('',name,-1,policy)
for name, policy in policies.get('default',{}).get('by_name',{}).items(): emit('',name,-1,policy)
for model, data in policies['models'].items():
    for name, policy in data.get('by_name',{}).items(): emit(model,name,-1,policy)
    for index, policy in data.get('by_index',{}).items():
        if not policy.get('name'): raise ValueError('Indexed policy requires expected source name')
        emit(model,policy['name'],int(index),policy)
lines += ['};']
(ROOT/'src/Semantics.generated.inc').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated native semantic metadata from', len(paths), 'owned inputs')
