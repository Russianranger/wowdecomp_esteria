#ifndef WOW_SOURCE_EXTENSION_EXTENSIONMGR_H
#define WOW_SOURCE_EXTENSION_EXTENSIONMGR_H

#include <cstdint>
#include <vector>
#include "WoW/Source/Extension/ScriptDefines/AllScriptsObjects.h"

class CDataStore;
class CM2Model;
class CM2Shared;
class WowClientDB_Base;
struct lua_State;

// The central script manager: loads the compiled-in extensions, holds one ScriptRegistry<T> per
// script type and exposes one OnXxx(...) dispatcher per hook. The client calls a dispatcher at the
// matching seam; the dispatcher walks the registry of the hook's script type and calls the virtual
// on every script. Extensions never call a dispatcher, only the services (Log,
// DeclareFrameScriptEvent).
class ExtensionMgr {
    friend class ScriptObject;

    private:
    ExtensionMgr();
    ~ExtensionMgr();

    public: /* Initialization */
    static ExtensionMgr* instance();

    // Opens Logs\Extensions.log and runs every compiled-in extension's entry point through the
    // table generated by Extensions/CMakeLists.txt. Each entry point instantiates its scripts,
    // whose constructors add them to their registry. No hook is fired here.
    void Initialize();

    // Deletes every registered script, empties the registries and closes the log.
    void Unload();

    void IncreaseScriptCount() { m_scriptCount++; }
    uint32_t GetScriptCount() const { return m_scriptCount; }

    // Writes one line to Logs\Extensions.log (flushed at once) and to the in-game console when the
    // console screen exists. The file is the record: console output is dropped before the console
    // font is loaded, which is the case for OnStartup.
    void Log(const char* format, ...);

    public: /* ClientScript */
    void OnStartup();
    void OnClientInitialized();
    void OnUpdate(float elapsedSec);
    void OnClientDestroy();
    void OnEnterWorld(uint32_t mapId);
    void OnLeaveWorld();
    void OnShutdown();

    public: /* WorldScript */
    void OnMapLoaded(uint32_t mapId, const char* mapName);
    void OnMapUnload();
    void OnWorldUpdate(float elapsedSec);

    public: /* RenderScript */
    void OnFrameBegin(float elapsedSec);
    void OnWorldRendered();
    void OnFrameEnd();

    public: /* NetScript */
    void OnMessageReceived(NETMESSAGE msgId, uint32_t timeReceived, CDataStore* msg);
    void OnMessageSent(CDataStore* msg);

    public: /* ModelScript */
    void OnModelSharedLoaded(CM2Shared* shared);
    void OnModelSkinLoaded(CM2Shared* shared);
    void OnModelSharedDestroy(CM2Shared* shared);
    void OnModelCreated(CM2Model* model);
    void OnModelLoaded(CM2Model* model);
    void OnModelDestroy(CM2Model* model);

    public: /* AssetScript */
    // True when a script redirected the open: redirect then holds the substitute path.
    bool OnFileOpen(const char* name, char* redirect, uint32_t redirectSize);

    public: /* ClientDBScript */
    void OnClientDBLoaded(WowClientDB_Base* db, const char* fileName);
    void OnClientDBInitialize();
    void OnClientDBShutdown();

    public: /* LuaScript */
    // Replaces the client's FrameScript_CreateEvents(names, count) call at each FrameScript rebuild
    // site. Fires LuaScript::OnFrameScriptInitialized for every script (where they declare their
    // events), then creates the engine's names followed by the declared names in one
    // FrameScript_CreateEvents call, so the engine's indices are unchanged and the declared
    // events get the indices DeclareFrameScriptEvent returned.
    void OnFrameScriptInitialized(FrameScriptContext context, const char** names, uint32_t count);

    // Service for LuaScript::OnFrameScriptInitialized only: returns the index name will have in the
    // event array being built, usable with FrameScript_SignalEvent once the hook has returned. An
    // engine event name returns the engine's index; a name declared twice returns the same index.
    // Outside the hook nothing is being built: the call is logged and returns UINT32_MAX.
    uint32_t DeclareFrameScriptEvent(const char* name);

    private:
    uint32_t m_scriptCount;
};

#define sExtensionMgr ExtensionMgr::instance()

// One registry per script type. The script type's constructor calls AddScript(this) (see
// ScriptDefines/*.cpp), so an extension registers a script simply by instantiating it. The list is
// filled while ExtensionMgr::Initialize() runs the entry points and is read-only afterwards; the
// dispatchers iterate it in insertion order.
template <class TScript>
class ScriptRegistry {
    public:
    typedef std::vector<TScript*> ScriptVector;

    // The actual list of scripts, in registration order.
    static ScriptVector ScriptPointerList;

    static void AddScript(TScript* const script) {
        if (!script) {
            return;
        }

        ScriptPointerList.push_back(script);
        sExtensionMgr->IncreaseScriptCount();
    }

    static void Clear() {
        for (TScript* script : ScriptPointerList) {
            delete script;
        }

        ScriptPointerList.clear();
    }
};

template <class TScript>
typename ScriptRegistry<TScript>::ScriptVector ScriptRegistry<TScript>::ScriptPointerList;

#endif
