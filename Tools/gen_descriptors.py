"""Generate extended update-field tables from the retained 12340 initializers.

Stock builds do not require Python. Extended builds run this at CMake configure
time and export limits.json as the server integration contract.
"""
import argparse
import json
from pathlib import Path
import re
from extend_class_masks import TABLES

ROOT = Path(__file__).resolve().parents[1]


def stock_initializer(path, symbol):
    source = (ROOT / path).read_text(encoding="utf-8")
    match = re.search(r"\b" + re.escape(symbol) + r"\[[^\n]+?\]\s*=\s*\{(.*?)\n\};", source, re.S)
    if not match:
        raise ValueError(f"Missing stock initializer: {symbol}")
    body = match.group(1).split("#else", 1)[0]
    return re.sub(r"^\s*#.*$", "", body, flags=re.M)


def stock_descriptors():
    body = stock_initializer("WoW/Source/ObjectMgrClient/Mirror.cpp", "PLAYER_DESCRIPTORS")
    return [(name, int(offset), int(count), int(kind), int(flags, 0))
            for name, offset, count, kind, flags in re.findall(
                r'\{\s*"([^"]+)",\s*(\d+),\s*(\d+),\s*(\d+),\s*(0x[0-9A-Fa-f]+)\s*\}', body)]


def build_tables(quests, containers):
    if not 25 <= quests <= 1000 or not 36 <= containers <= 254:
        raise ValueError("Supported capacities: 25..1000 quests, 36..254 container slots")
    delta = 5 * (quests - 25)
    stock = stock_descriptors()
    assert len(stock) == 215
    descriptors = list(stock[:9])
    # Retain original descriptor names, including slot 1's _4 suffix.
    for slot in range(quests):
        for suffix, offset, count, kind, flags in ((1, 0, 1, 1, 0x40), (2, 1, 1, 1, 2), (3, 2, 2, 2, 2), (4 if slot == 0 else 5, 4, 1, 1, 2)):
            descriptors.append((f"PLAYER_QUEST_LOG_{slot + 1}_{suffix}", 10 + 5 * slot + offset, count, kind, flags))
    descriptors.extend((name, offset + delta, count, kind, flags) for name, offset, count, kind, flags in stock[109:])
    shared = list(range(2, 175 + delta))
    local_body = stock_initializer("WoW/Source/Object/Player.cpp", "CGPlayer::s_localMirrorFields")
    local = [int(n, 0) + delta for n in re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", local_body)]
    assert len(local) == 870
    return descriptors, shared, local, list(range(2, 2 + 2 * containers))


def write_tables(output, quests, containers, max_classes=32):
    if not 32 <= max_classes <= 254:
        raise ValueError("Supported class ceiling: 32..254")
    output.mkdir(parents=True, exist_ok=True)
    descriptors, shared, local, container = build_tables(quests, containers)
    files = {"PlayerDescriptors.inc": "\n".join(
        f'    {{ "{name}", {offset}, {count}, {kind}, 0x{flags:X} }},' for name, offset, count, kind, flags in descriptors)}
    for name, values in (("PlayerMirrorFields.inc", shared), ("PlayerLocalMirrorFields.inc", local), ("ContainerMirrorFields.inc", container)):
        files[name] = "\n".join("    " + ", ".join(f"0x{v:X}" for v in values[i:i + 16]) + "," for i in range(0, len(values), 16))
    for name, body in files.items():
        target = output / name
        text = "// Generated by Tools/gen_descriptors.py; do not edit.\n" + body + "\n"
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8", newline="\n")
    delta = 5 * (quests - 25)
    manifest = {"build": 12340, "quest_slots": quests, "container_slots": containers,
                "max_class_id": max_classes, "class_mask_words": 8 if max_classes > 32 else 1,
                "class_masks": {"byte_order": "little-endian", "word_order": "least-significant first",
                                "item_skill_talent_faction_bit": "classId - 1",
                                "who_realm_tracking_bit": "classId"},
                "active_player_dwords": 1326 + delta, "remote_player_dwords": 324 + delta,
                "required_mask_dwords": (1326 + delta + 31) // 32,
                "container_dwords": 66 + 2 * containers, "quest_remove_slot_bytes": 2 if quests > 255 else 1,
                "quest_remove_opcode": "CMSG_QUEST_LOG_REMOVE_QUEST",
                "player_field_base_dword": 148,
                "player_fields": [dict(name=name, offset=148 + offset, count=count, type=kind, flags=flags)
                                  for name, offset, count, kind, flags in descriptors]}
    words = manifest["class_mask_words"]
    manifest["class_mask_bytes"] = 4 * words
    manifest["item_cache_version"] = 6 if words > 1 else 5
    manifest["petition_cache_version"] = 2 if words > 1 else 1
    manifest["character_restriction_trailer_bytes"] = 10 * 4 * words
    manifest["class_mask_dbcs"] = {
        name: {"columns": fields + (words - 1) * len(masks),
               "row_bytes": 4 * (fields + (words - 1) * len(masks)),
               "mask_columns": [column + (words - 1) * index for index, column in enumerate(masks)]}
        for name, (fields, masks) in TABLES.items()}
    (output / "limits.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quest-slots", type=int, default=25)
    parser.add_argument("--container-slots", type=int, default=36)
    parser.add_argument("--max-classes", type=int, default=32)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write_tables(args.output, args.quest_slots, args.container_slots, args.max_classes)
